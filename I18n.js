// "auto" follows the environment the shell was started with; anything else is
// taken as a locale name ("de", "pt_BR"). Unknown languages fall back to English.
function resolve(setting, env) {
  var candidates = []
  var chosen = String(setting || "auto").trim()
  if (chosen !== "" && chosen.toLowerCase() !== "auto") candidates.push(chosen)
  var language = String(env.LANGUAGE || "")
  if (language !== "") candidates = candidates.concat(language.split(":"))
  candidates.push(env.LC_ALL, env.LC_MESSAGES, env.LANG)
  for (var i = 0; i < candidates.length; i++) {
    var code = String(candidates[i] || "").toLowerCase().split(/[_.@-]/)[0]
    if (code === "c" || code === "posix") continue
    if (strings[code]) return code
  }
  return "en"
}

function tr(lang, key, args) {
  var table = strings[lang] || strings.en
  var text = table[key] !== undefined ? table[key] : strings.en[key]
  if (text === undefined) return key
  if (!args) return text
  // One pass, so an argument that itself contains "{1}" is not substituted again.
  return text.replace(/\{(\d+)\}/g, function(match, index) {
    return Number(index) < args.length ? String(args[Number(index)]) : match
  })
}
